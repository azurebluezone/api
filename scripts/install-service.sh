#!/usr/bin/env bash
# install-service.sh — (re)generate + enable the systemd user unit
# ═══════════════════════════════════════════════════════════════════════
#
#   scripts/install-service.sh            write unit, daemon-reload, enable
#   scripts/install-service.sh --start    … and start it now
#   scripts/install-service.sh --remove   disable + delete the unit
#
# WHY THIS FILE EXISTS
#   The unit file used to live only in ~/.config/systemd/user with absolute
#   paths baked in — after a fresh OS install it would be gone and the docs
#   would not reproduce it. This script REGENERATES the unit from wherever
#   the repo currently is, so "clone → .env → run this script" is the whole
#   setup. Nothing here hardcodes a username, home directory or node path.
#
# It is idempotent: running it again just rewrites the unit with current
# paths (e.g. after moving the checkout).
set -uo pipefail

UNIT_NAME="zombiecoder-gateway.service"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
UNIT_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user"
UNIT_FILE="$UNIT_DIR/$UNIT_NAME"
LOG_DIR="$ROOT/logs"
MODE="${1:-install}"

command -v systemctl >/dev/null 2>&1 || { echo "systemctl not found — no systemd on this machine."; exit 1; }

case "$MODE" in
  --remove)
    systemctl --user disable --now "$UNIT_NAME" 2>/dev/null || true
    rm -f "$UNIT_FILE"
    systemctl --user daemon-reload
    echo "removed $UNIT_FILE"
    exit 0
    ;;
  --start|install|"") ;;
  *) echo "usage: $0 [--start|--remove]"; exit 2 ;;
esac

mkdir -p "$UNIT_DIR" "$LOG_DIR"

# ── the unit, with every path derived from $ROOT ─────────────────────────────
cat > "$UNIT_FILE" <<EOF
[Unit]
# Generated by scripts/install-service.sh — DO NOT hand-edit paths here;
# re-run that script instead. It is regenerated with the repo's current
# location every time it runs (fresh install / moved checkout).
Description=ZombieCoder Mission Barisal Gateway (port 5050)
Documentation=file://$ROOT/README.md
After=network-online.target
Wants=network-online.target
# Stop retrying after 10 failures in 5 minutes so a broken config does not spin.
StartLimitBurst=10
StartLimitIntervalSec=300

[Service]
Type=simple
WorkingDirectory=$ROOT
# The wrapper pre-flights (node version, .env, ports), loads .env, clears
# stale UDS sockets, then exec's node outside the capability sandbox. Running
# node directly under this unit aborted with status=218/CAPABILITIES because
# the server's own sandboxing and systemd's collided.
ExecStart=$ROOT/scripts/zombiecoder-gateway.sh

# Restart policy: 2s grace, then retry; give up after 10 failures in 5 minutes.
Restart=always
RestartSec=2

# Logging — both files also feed logs/ alongside the unified logs/zc.jsonl.
StandardOutput=append:$LOG_DIR/systemd-out.log
StandardError=append:$LOG_DIR/systemd-err.log

# Hardening — the server reads its own tree and writes data/, logs/, cache/.
ProtectSystem=full
ProtectHome=read-only
ReadWritePaths=$ROOT/data $ROOT/logs $ROOT/cache
# ProtectKernelModules=true is deliberately absent: in a *user* unit it makes
# systemd abort the exec (status=218/CAPABILITIES). Verified 2026-09-30.
ProtectControlGroups=true

[Install]
WantedBy=default.target
EOF

systemctl --user daemon-reload
systemctl --user enable "$UNIT_NAME" >/dev/null 2>&1 && echo "enabled  $UNIT_NAME" || echo "enable failed (is the user bus reachable?)"

# Lingering: without it the user's units die at logout and do NOT start on
# boot before login. Needs no root for your own account on most setups.
if [ "$(loginctl show-user "$USER" -p Linger --value 2>/dev/null)" != "yes" ]; then
  if loginctl enable-linger "$USER" 2>/dev/null; then
    echo "lingering enabled — units now survive reboot without login"
  else
    echo "NOTE: could not enable lingering (needs admin). Run once:"
    echo "      sudo loginctl enable-linger $USER"
  fi
fi

echo "unit written → $UNIT_FILE"
echo "  paths: root=$ROOT"
echo "  node : $(ls -d "$HOME"/.nvm/versions/node/v2[4-9]*.*/bin/node 2>/dev/null | sort -V | tail -1 || echo '/usr/bin/node (wrapper will warn)')"
echo "  logs : $LOG_DIR (unified: logs/zc.jsonl)"

if [ "$MODE" = "--start" ]; then
  systemctl --user restart "$UNIT_NAME"
  sleep 3
  systemctl --user is-active "$UNIT_NAME" && echo "started ✓" || { echo "FAILED — see $LOG_DIR/systemd-err.log"; exit 1; }
fi
